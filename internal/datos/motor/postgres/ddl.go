package postgres

import (
	"fmt"
	"strings"

	"github.com/lib/pq"
	"github.com/zara-te05/Marga/internal/modelos/esquema"
)

// Dialecto escribe objetos del esquema como DDL de PostgreSQL.
type Dialecto struct{}

func (Dialecto) DDLTabla(t esquema.Tabla) string     { return DDLTabla(t) }
func (Dialecto) DDLEnum(e esquema.Enum) string       { return DDLEnum(e) }
func (Dialecto) DDLFuncion(f esquema.Funcion) string { return DDLFuncion(f) }
func (Dialecto) DDLVista(v esquema.Vista) string     { return DDLVista(v) }
func (Dialecto) DDLTrigger(t esquema.Trigger) string { return DDLTrigger(t) }

// DDL reconstruye la definición de la tabla de forma legible.
func DDLTabla(t esquema.Tabla) string {
	var b strings.Builder
	fmt.Fprintf(&b, "CREATE TABLE %s (\n", t.Nombre)
	var partes []string
	for _, c := range t.Columnas {
		partes = append(partes, "    "+c.Nombre+" "+c.Tipo+Modificadores(c))
	}
	if len(t.PK) > 0 {
		partes = append(partes, "    PRIMARY KEY ("+strings.Join(t.PK, ", ")+")")
	}
	for _, f := range t.FKs {
		p := fmt.Sprintf("    FOREIGN KEY (%s) REFERENCES %s (%s)", strings.Join(f.Columnas, ", "), f.Tabla, strings.Join(f.RefColumnas, ", "))
		if f.AlBorrar != "" {
			p += " ON DELETE " + f.AlBorrar
		}
		partes = append(partes, p)
	}
	for _, c := range t.Checks {
		partes = append(partes, "    CONSTRAINT "+c.Nombre+" "+c.Definicion)
	}
	b.WriteString(strings.Join(partes, ",\n"))
	b.WriteString("\n);")
	for _, i := range t.Indices {
		b.WriteString("\n" + i.Definicion + ";")
	}
	return b.String() + "\n"
}

// Modificadores devuelve " NOT NULL DEFAULT …" / " GENERATED … AS IDENTITY" de una columna.
func Modificadores(c esquema.Columna) string {
	s := ""
	switch c.Identidad {
	case "a":
		s += " GENERATED ALWAYS AS IDENTITY"
	case "d":
		s += " GENERATED BY DEFAULT AS IDENTITY"
	}
	if !c.Nulo && c.Identidad == "" {
		s += " NOT NULL"
	}
	if c.Defecto != "" {
		s += " DEFAULT " + c.Defecto
	}
	return s
}

func DDLFuncion(f esquema.Funcion) string { return strings.TrimRight(f.Definicion, "\n; ") + ";\n" }

// Crear devuelve el CREATE de la vista (y sus índices si es materializada).
func DDLVista(v esquema.Vista) string {
	tipo := "VIEW"
	if v.Materializada {
		tipo = "MATERIALIZED VIEW"
	}
	opc := ""
	if v.Opciones != "" {
		opc = " WITH (" + v.Opciones + ")"
	}
	s := fmt.Sprintf("CREATE %s %s%s AS\n%s;\n", tipo, v.Nombre, opc, v.Definicion)
	for _, i := range v.Indices {
		s += i.Definicion + ";\n"
	}
	return s
}

func DDLTrigger(t esquema.Trigger) string {
	s := t.Definicion + ";\n"
	if t.Desactivado {
		s += fmt.Sprintf("ALTER TABLE %s DISABLE TRIGGER %s;\n", t.Tabla, t.Nombre)
	}
	return s
}

func DDLEnum(e esquema.Enum) string {
	vals := make([]string, len(e.Valores))
	for i, v := range e.Valores {
		vals[i] = pq.QuoteLiteral(v)
	}
	return fmt.Sprintf("CREATE TYPE %s AS ENUM (%s);\n", e.Nombre, strings.Join(vals, ", "))
}
